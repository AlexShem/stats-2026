"""Расписание занятий: осенний семестр 2026, вторники (с переносами и контрольной)."""

from __future__ import annotations

import datetime as dt

#: Первый вторник серии. Занятия начались неделей позже календарного начала
#: семестра, первый семинар 8 сентября, дальше строго по вторникам.
FIRST_SEMINAR = dt.date(2026, 9, 8)

#: Число занятий в семестре (семинары и контрольные вместе).
SEMINAR_COUNT = 16

#: Перенесённые занятия: плановый вторник → фактическая дата.
#: Семинар 6 проведён в пятницу 9 октября вместо вторника 13 октября.
#: Занятие вторника 20 октября перенесено на пятницу 6 ноября (семинар 8).
RESCHEDULED: dict[dt.date, dt.date] = {
    dt.date(2026, 10, 13): dt.date(2026, 10, 9),
    dt.date(2026, 10, 20): dt.date(2026, 11, 6),
}

#: Плановые вторники серии, без учёта переносов.
TUESDAYS: list[dt.date] = [FIRST_SEMINAR + dt.timedelta(weeks=i) for i in range(SEMINAR_COUNT)]

#: Контрольные работы: дата → название. Это занятия, но не семинары: главы
#: и раздатки у них нет, номера семинара они не получают.
MIDTERMS: dict[dt.date, str] = {
    dt.date(2026, 11, 3): "Контрольная работа по теории вероятностей",
}

#: Фактические даты всех занятий (семинаров и контрольных) по времени.
CLASS_DATES: list[dt.date] = sorted(RESCHEDULED.get(d, d) for d in TUESDAYS)

#: Даты семинаров по порядку. Номер семинара есть номер по времени среди
#: семинаров: контрольная 3 ноября номера не занимает, 6 ноября семинар 8.
SEMINAR_DATES: list[dt.date] = [d for d in CLASS_DATES if d not in MIDTERMS]


def seminar_date(number: int) -> dt.date:
    """Дата семинара по его номеру (нумерация с 1)."""
    if not 1 <= number <= len(SEMINAR_DATES):
        raise ValueError(
            f"Номер семинара должен быть от 1 до {len(SEMINAR_DATES)}, получено {number}"
        )
    return SEMINAR_DATES[number - 1]


def format_ru(date: dt.date) -> str:
    """Дата по-русски: '8 сентября 2026'."""
    months = [
        "января",
        "февраля",
        "марта",
        "апреля",
        "мая",
        "июня",
        "июля",
        "августа",
        "сентября",
        "октября",
        "ноября",
        "декабря",
    ]
    return f"{date.day} {months[date.month - 1]} {date.year}"
